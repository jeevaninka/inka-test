const DropdownMenu = DropdownMenuPrimitive.Root;

function HoverDropdownMenu({ children, hoverDelay = 100, hoverLeaveDelay = 200, ...props }: React.ComponentProps<typeof DropdownMenuPrimitive.Root> & { hoverDelay?: number; hoverLeaveDelay?: number }) {
  const [internalOpen, setInternalOpen] = React.useState(false);
  const isControlled = props.open !== undefined;
  const open = isControlled ? props.open : internalOpen;
  
  const handleOpenChange = (newOpen: boolean) => {
    if (props.onOpenChange) props.onOpenChange(newOpen);
    if (!isControlled) setInternalOpen(newOpen);
  };

  const timeoutRef = React.useRef<NodeJS.Timeout | null>(null);
  const isHoveringRef = React.useRef(false);

  const handleMouseEnter = (e: React.MouseEvent) => {
    e.stopPropagation();
    isHoveringRef.current = true;
    if (timeoutRef.current) clearTimeout(timeoutRef.current);
    timeoutRef.current = setTimeout(() => {
      if (isHoveringRef.current) handleOpenChange(true);
    }, hoverDelay);
  };

  const handleMouseLeave = (e: React.MouseEvent) => {
    e.stopPropagation();
    isHoveringRef.current = false;
    if (timeoutRef.current) clearTimeout(timeoutRef.current);
    timeoutRef.current = setTimeout(() => {
      if (!isHoveringRef.current) handleOpenChange(false);
    }, hoverLeaveDelay);
  };

  return (
    <DropdownMenuPrimitive.Root modal={false} {...props} open={open} onOpenChange={handleOpenChange}>
      <div 
        onMouseEnter={handleMouseEnter} 
        onMouseLeave={handleMouseLeave} 
        className="inline-block relative" 
        onClick={(e) => e.stopPropagation()}
      >
        {children}
      </div>
    </DropdownMenuPrimitive.Root>
  );
}
